#!/usr/bin/env node
// Exports the Svelte locale bundles (src/i18n/locales/*.ts) to the YAML files
// read by rust-i18n in the GPUI app.
//
// This is the temporary bridge described in docs/GPUI-MIGRATION.md (13.1):
// the TypeScript bundles stay the source of truth while the Tauri shell is
// still shippable, and the YAML files are generated. Once the GPUI app replaces
// the webview (Phase 6), the YAML becomes the source.
//
// Run with: node --experimental-strip-types scripts/export-i18n.mjs
//
// Placeholder syntax: the TS bundles use `{name}`; rust-i18n uses `%{name}`.
// The export converts them and fails if a locale is missing a key or drops a
// placeholder, so parity is a script gate as well as a Rust test.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(root, "src", "i18n", "locales");
const outDir = join(root, "crates", "open-scrcpy-gpui", "locales");

/** Locale file -> BCP 47 code used by rust-i18n and the app settings. */
const LOCALES = [
    ["en", "en"],
    ["fr", "fr"],
    ["pt-BR", "pt-BR"],
    ["zh-CN", "zh-CN"],
    ["zh-TW", "zh-TW"],
    ["ru", "ru"],
    ["id", "id"],
    ["ar", "ar"]
];

const PLACEHOLDER = /(?<!%)\{([A-Za-z_][A-Za-z0-9_]*)\}/g;

function convertPlaceholders(value) {
    return value.replace(PLACEHOLDER, "%{$1}");
}

function placeholdersOf(value) {
    return [...value.matchAll(PLACEHOLDER)].map((match) => match[1]).sort();
}

function flatten(value, prefix = "", out = new Map()) {
    for (const [key, child] of Object.entries(value)) {
        const path = prefix ? `${prefix}.${key}` : key;
        if (child && typeof child === "object" && !Array.isArray(child)) {
            flatten(child, path, out);
        } else if (typeof child === "string") {
            out.set(path, child);
        } else {
            throw new Error(`unsupported locale value at ${path}: ${typeof child}`);
        }
    }
    return out;
}

function yamlKey(key) {
    return /^[A-Za-z0-9_-]+$/.test(key) ? key : JSON.stringify(key);
}

function yamlString(value) {
    const escaped = value
        .replace(/\\/g, "\\\\")
        .replace(/"/g, '\\"')
        .replace(/\n/g, "\\n")
        .replace(/\t/g, "\\t");
    return `"${escaped}"`;
}

function buildTree(byKey) {
    const root = {};
    for (const [path, translations] of byKey) {
        const parts = path.split(".");
        let node = root;
        for (const part of parts.slice(0, -1)) {
            node[part] ??= {};
            node = node[part];
        }
        node[parts[parts.length - 1]] = new Map(translations);
    }
    return root;
}

function emitNode(node, depth, lines) {
    const indent = "  ".repeat(depth);
    for (const [key, value] of Object.entries(node)) {
        lines.push(`${indent}${yamlKey(key)}:`);
        if (value instanceof Map) {
            for (const [code, text] of value) {
                lines.push(`${"  ".repeat(depth + 1)}${yamlKey(code)}: ${yamlString(text)}`);
            }
        } else {
            emitNode(value, depth + 1, lines);
        }
    }
}

function toYaml(byKey) {
    const lines = [
        "# Generated by scripts/export-i18n.mjs from src/i18n/locales/*.ts.",
        "# Do not edit by hand: change the TypeScript bundles and re-run the export.",
        "#",
        "# rust-i18n v2 shape: translation keys first, locale leaves last.",
        "_version: 2"
    ];
    emitNode(buildTree(byKey), 0, lines);
    return lines.join("\n") + "\n";
}

async function loadLocale(file) {
    const module = await import(join(sourceDir, `${file}.ts`));
    const values = Object.values(module);
    if (values.length !== 1) {
        throw new Error(`${file}.ts must export exactly one locale object`);
    }
    return values[0];
}

async function main() {
    const reference = flatten(await loadLocale("en"));
    if (reference.size === 0) {
        throw new Error("no keys exported");
    }

    // path -> [(locale, converted text)], in the catalog order.
    const byKey = new Map();
    for (const [file, code] of LOCALES) {
        const flat = flatten(await loadLocale(file));
        for (const key of reference.keys()) {
            if (!flat.has(key)) {
                throw new Error(`${code}: missing key ${key}`);
            }
            const expected = placeholdersOf(reference.get(key));
            const actual = placeholdersOf(flat.get(key));
            if (expected.join(",") !== actual.join(",")) {
                throw new Error(
                    `${code}: placeholders differ at ${key} (${expected} vs ${actual})`
                );
            }
        }
        for (const key of flat.keys()) {
            if (!reference.has(key)) {
                throw new Error(`${code}: extra key ${key}`);
            }
        }
        for (const [key, value] of flat) {
            if (!byKey.has(key)) {
                byKey.set(key, []);
            }
            byKey.get(key).push([code, convertPlaceholders(value)]);
        }
    }

    await mkdir(outDir, { recursive: true });
    const target = join(outDir, "ui.yml");
    await writeFile(target, toYaml(byKey), "utf8");
    console.log(
        `parity: ${LOCALES.length} locales, ${reference.size} keys -> ${target}`
    );
}

main().catch((error) => {
    console.error(`export-i18n: ${error.message}`);
    process.exit(1);
});
